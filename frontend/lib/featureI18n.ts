import { EXTRA_LOCALE_COPY } from "./featureI18nLocales";

const DICTS: Record<string, Dict> = { en, hu, ...EXTRA_LOCALE_COPY };

/** Translate a feature copy key. Missing keys fall back to English, then to the key itself. */
export function ft(key: string, locale: string = "en", params?: Record<string, string | number>): string {
  const dict = DICTS[locale] ?? en;
  const template = dict[key] ?? en[key] ?? key;
  if (!params) return template;
  return Object.entries(params).reduce((text, [name, value]) => text.replace(`{${name}}`, String(value)), template);
}

/** Keys missing from each locale compared with English. Empty for every supported locale. */
export function missingFeatureKeys(locale: string): string[] {
  const dict = DICTS[locale];
  if (!dict) return Object.keys(en);
  return Object.keys(en).filter((key) => !(key in dict));
}

